#[derive(Parser)]
#[command(
    name = "reprocrate",
    version,
    about = "Turn bugs into reproducible reports."
)]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand)]
enum Commands {
    /// Run a command WITHOUT a shell, then save a local, sanitized report.
    Capture {
        /// JSON report destination (will not overwrite an existing file).
        #[arg(long, default_value = "reprocrate-report.json")]
        output: PathBuf,
        /// Optional Markdown report destination.
        #[arg(long)]
        markdown: Option<PathBuf>,
        /// Execution timeout in seconds (1..=86400).
        #[arg(long, default_value_t = 30)]
        timeout_seconds: u64,
        /// Output byte budget per stream (1..=10485760).
        #[arg(long, default_value_t = 65_536)]
        max_output_bytes: usize,
        #[arg(long, value_enum, default_value_t = ProfileArg::Standard)]
        profile: ProfileArg,
        /// Optional human-readable title.
        #[arg(long)]
        title: Option<String>,
        /// Explicit command and arguments. Precede them with --.
        #[arg(last = true, num_args = 1.., required = true)]
        command: Vec<OsString>,
    },
    /// Analyze a selected log (or '-' for stdin) without executing its contents.
    Analyze {
        /// Path to textual log file, or '-' to read standard input.
        input: PathBuf,
        /// Heuristic format detector or an explicitly selected parser.
        #[arg(long, value_enum, default_value_t = FormatArg::Auto)]
        format: FormatArg,
        /// Destination for sanitized JSON analysis (no overwrite).
        #[arg(long, default_value = "reprocrate-analysis.json")]
        output: PathBuf,
        /// Optional sanitized Markdown analysis destination.
        #[arg(long)]
        markdown: Option<PathBuf>,
        /// Maximum bytes read from the selected log (1..=8388608).
        #[arg(long, default_value_t = 1_048_576)]
        max_input_bytes: usize,
    },
    /// Re-scan, selectively exclude fields and preview a JSON report before sharing.
    Review {
        /// Existing report JSON generated by ReproCrate.
        input: PathBuf,
        /// New JSON path for the edited review candidate (never overwrite).
        #[arg(long)]
        output: Option<PathBuf>,
        /// Local UTF-8 file containing one literal to mask on each line.
        #[arg(long)]
        masks_file: Option<PathBuf>,
        /// Explicitly print the *entire* edited JSON payload to the terminal.
        #[arg(long)]
        preview: bool,
        #[arg(long)]
        exclude_stdout: bool,
        #[arg(long)]
        exclude_stderr: bool,
        #[arg(long)]
        exclude_arguments: bool,
        #[arg(long)]
        exclude_executable: bool,
        #[arg(long)]
        exclude_analysis: bool,
    },
    /// Create, inspect, verify or safely extract a portable diagnostic ZIP.
    Bundle {
        #[command(subcommand)]
        action: BundleActions,
    },
    /// Compare two saved reports without exporting raw output or arguments.
    Compare {
        baseline: PathBuf,
        candidate: PathBuf,
        #[arg(long, default_value = "reprocrate-comparison.json")]
        output: PathBuf,
        #[arg(long)]
        markdown: Option<PathBuf>,
    },
    /// Produce or inspect a structured, non-executable reproduction guide.
    Recipe {
        #[command(subcommand)]
        action: RecipeActions,
    },
    /// Export a manually reviewed, inert issue draft for GitHub/GitLab/Gitea/Markdown.
    Issue {
        #[command(subcommand)]
        action: IssueActions,
    },
    /// Print the small amount of environment information captured by profiles.
    Doctor {
        #[arg(long)]
        json: bool,
    },
    /// Display metadata from a bounded, valid ReproCrate JSON report.
    Inspect { path: PathBuf },
}

#[derive(Subcommand)]
enum BundleActions {
    /// Create ZIP only from explicitly approved, locally reviewed files.
    Create {
        #[arg(long)]
        report: PathBuf,
        #[arg(long)]
        output: PathBuf,
        /// Each attachment is included as bytes under a generated safe name.
        #[arg(long)]
        attachment: Vec<PathBuf>,
        /// Confirm manual review of the report and every attachment.
        #[arg(long)]
        acknowledge_reviewed: bool,
    },
    /// Verify and list every allowed member and its SHA-256.
    Inspect { input: PathBuf },
    /// Verify manifest, report identity, names, limits and checksums.
    Verify { input: PathBuf },
    /// Extract only fully validated members into a new, nonexistent directory.
    Extract {
        input: PathBuf,
        destination: PathBuf,
    },
}

#[derive(Subcommand)]
enum RecipeActions {
    /// Export a manual troubleshooting checklist from a saved report.
    Create {
        #[arg(long)]
        report: PathBuf,
        #[arg(long, default_value = "reprocrate-recipe.json")]
        output: PathBuf,
        #[arg(long)]
        markdown: Option<PathBuf>,
        /// Include the report's command and arguments only after approval.
        #[arg(long)]
        include_command: bool,
        /// Explicitly acknowledge reviewing the command and arguments.
        #[arg(long)]
        acknowledge_reviewed: bool,
    },
    /// Validate an inert recipe file and show only its metadata.
    Inspect { input: PathBuf },
}

#[derive(Subcommand)]
enum IssueActions {
    /// Save an offline Markdown draft (never posts an issue).
    Export {
        #[arg(long)]
        report: PathBuf,
        #[arg(long, default_value = "reprocrate-issue.md")]
        output: PathBuf,
        #[arg(long, value_enum, default_value_t = IssueTargetArg::Github)]
        target: IssueTargetArg,
        /// Opt in to the report title, which may reveal sensitive details.
        #[arg(long)]
        include_title: bool,
        /// Opt in to high-level OS and architecture information.
        #[arg(long)]
        include_environment: bool,
        /// Opt in to summary categories, never raw log messages.
        #[arg(long)]
        include_categories: bool,
        /// Affirmatively acknowledge manually reviewing the source report.
        #[arg(long)]
        acknowledge_reviewed: bool,
    },
}

#[derive(Clone, Copy, Debug, ValueEnum)]
enum IssueTargetArg {
    Github,
    Gitlab,
    Gitea,
    Generic,
}
impl From<IssueTargetArg> for IssueTarget {
    fn from(value: IssueTargetArg) -> Self {
        match value {
            IssueTargetArg::Github => Self::Github,
            IssueTargetArg::Gitlab => Self::Gitlab,
            IssueTargetArg::Gitea => Self::Gitea,
            IssueTargetArg::Generic => Self::Generic,
        }
    }
}

#[derive(Clone, Copy, Debug, ValueEnum)]
enum ProfileArg {
    Minimal,
    Standard,
}
impl From<ProfileArg> for CaptureProfile {
    fn from(value: ProfileArg) -> Self {
        match value {
            ProfileArg::Minimal => Self::Minimal,
            ProfileArg::Standard => Self::Standard,
        }
    }
}

fn create_new_report(path: &Path, bytes: &[u8]) -> Result<(), Box<dyn Error>> {
    let mut file = OpenOptions::new().write(true).create_new(true).open(path)?;
    if let Err(error) = file.write_all(bytes).and_then(|_| file.sync_all()) {
        // Do not leave behind a misleading successful-looking partial export.
        drop(file);
        let _ = fs::remove_file(path);
        return Err(error.into());
    }
    Ok(())
}

fn import_json(path: &Path) -> Result<Report, Box<dyn Error>> {
    let file = File::open(path)?;
    if file.metadata()?.len() > 4 * 1024 * 1024 {
        return Err("report exceeds the 4 MiB import limit".into());
    }
    let mut bytes = Vec::new();
    file.take(4 * 1024 * 1024 + 1).read_to_end(&mut bytes)?;
    if bytes.len() > 4 * 1024 * 1024 {
        return Err("report exceeds the 4 MiB import limit".into());
    }
    let report: Report = serde_json::from_slice(&bytes)?;
    if report.schema_version != SCHEMA_VERSION {
        return Err(format!(
            "unsupported schema {}; this CLI only reads {}",
            report.schema_version, SCHEMA_VERSION
        )
        .into());
    }
    Ok(report)
}

fn run() -> Result<(), Box<dyn Error>> {
    let cli = Cli::parse();
    match cli.command {
        Commands::Analyze {
            input,
            format,
            output,
            markdown,
            max_input_bytes,
        } => {
            run_analysis(input, format, output, markdown, max_input_bytes)?;
        }
        Commands::Review {
            input,
            output,
            masks_file,
            preview,
            exclude_stdout,
            exclude_stderr,
            exclude_arguments,
            exclude_executable,
            exclude_analysis,
        } => {
            run_review(
                input,
                output,
                masks_file,
                preview,
                exclude_stdout,
                exclude_stderr,
                exclude_arguments,
                exclude_executable,
                exclude_analysis,
            )?;
        }
        Commands::Bundle { action } => match action {
            BundleActions::Create {
                report,
                output,
                attachment,
                acknowledge_reviewed,
            } => {
                run_bundle_create(report, output, attachment, acknowledge_reviewed)?;
            }
            BundleActions::Inspect { input } => run_bundle_inspect(input, false)?,
            BundleActions::Verify { input } => run_bundle_inspect(input, true)?,
            BundleActions::Extract { input, destination } => {
                run_bundle_extract(input, destination)?
            }
        },
        Commands::Compare {
            baseline,
            candidate,
            output,
            markdown,
        } => {
            run_compare(baseline, candidate, output, markdown)?;
        }
        Commands::Recipe { action } => match action {
            RecipeActions::Create {
                report,
                output,
                markdown,
                include_command,
                acknowledge_reviewed,
            } => {
                run_recipe_create(
                    report,
                    output,
                    markdown,
                    include_command,
                    acknowledge_reviewed,
                )?;
            }
            RecipeActions::Inspect { input } => run_recipe_inspect(input)?,
        },
        Commands::Issue { action } => match action {
            IssueActions::Export {
                report,
                output,
                target,
                include_title,
                include_environment,
                include_categories,
                acknowledge_reviewed,
            } => {
                run_issue_export(
                    report,
                    output,
                    target.into(),
                    IssueOptions {
                        include_title,
                        include_environment,
                        include_categories,
                        acknowledge_reviewed,
                    },
                )?;
            }
        },
        Commands::Doctor { json } => {
            let env = inspect_environment(CaptureProfile::Standard);
            if json {
                println!("{}", serde_json::to_string_pretty(&env)?);
            } else {
                println!("ReproCrate {}", env!("CARGO_PKG_VERSION"));
                println!("OS: {}", env.os);
                println!("Architecture: {}", env.architecture);
                println!(
                    "Available parallelism: {}",
                    env.available_parallelism.unwrap_or(0)
                );
                println!(
                    "No hostnames, environment variables, usernames or network IDs are collected."
                );
            }
        }
        Commands::Inspect { path } => {
            let report = import_json(&path)?;
            println!("Report: {}", report.report_id);
            println!("Title: {}", report.title);
            println!("Schema: {}", report.schema_version);
            println!("Program: {}", report.capture.executable);
            println!(
                "Exit code: {}",
                report
                    .capture
                    .exit_code
                    .map(|n| n.to_string())
                    .unwrap_or_else(|| "unavailable".into())
            );
            println!("Duration: {} ms", report.capture.duration_ms);
            println!("Timed out: {}", report.capture.timed_out);
            println!("Warnings: {}", report.warnings.len());
            println!("Inspect the original report before sharing.");
        }
        Commands::Capture {
            output,
            markdown,
            timeout_seconds,
            max_output_bytes,
            profile,
            title,
            command,
        } => {
            if markdown.as_deref() == Some(output.as_path()) {
                return Err("--output and --markdown must be different paths".into());
            }
            if output.exists() || markdown.as_ref().is_some_and(|path| path.exists()) {
                return Err(
                    "an output file already exists; choose a new name (overwrite is disabled)"
                        .into(),
                );
            }
            let options = CaptureOptions {
                timeout: Duration::from_secs(timeout_seconds),
                max_output_bytes_per_stream: max_output_bytes,
            };
            let captured = capture_command(&command, &options)?;
            let title = title.unwrap_or_else(|| format!("Capture of {}", captured.executable));
            let report = Report::new(title, inspect_environment(profile.into()), captured);
            let json = serde_json::to_vec_pretty(&report)?;
            create_new_report(&output, &json)?;
            if let Some(md_path) = markdown {
                create_new_report(&md_path, render_markdown(&report).as_bytes())?;
                println!("Markdown report: {}", md_path.display());
            }
            println!("JSON report: {}", output.display());
            println!("Exit code: {:?}", report.capture.exit_code);
            println!("Timed out: {}", report.capture.timed_out);
            println!("Redaction pattern matches: {}", report.redaction_matches);
            eprintln!(
                "Review every field and log excerpt before sharing. Masking is not guaranteed."
            );
        }
    }
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("reprocrate: {error}");
        std::process::exit(2);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn capture_syntax_with_separator_parses() {
        let parsed = Cli::try_parse_from(["reprocrate", "capture", "--", "cargo", "test"])
            .expect("valid capture syntax");
        match parsed.command {
            Commands::Capture { command, .. } => {
                assert_eq!(
                    command,
                    vec![OsString::from("cargo"), OsString::from("test")]
                );
            }
            _ => panic!("unexpected subcommand"),
        }
    }

    #[test]
    fn invalid_capture_omitting_program_is_rejected() {
        assert!(Cli::try_parse_from(["reprocrate", "capture", "--"]).is_err());
    }
}
